namespace App;

use App\DocumentValidation\DocumentValidator;
use App\DocumentValidation\Rule\ContentPatternRule;
use App\DocumentValidation\Rule\MaxDocumentSizeRule;
use App\DocumentValidation\Rule\MetadataAllowedValuesRule;
use App\DocumentValidation\Rule\ProhibitedWordsRule;
use App\DocumentValidation\Rule\RequiredMetadataRule;
use App\DocumentValidation\RuleFactory;
use App\DocumentValidation\ValidationRuleProvider;
use App\Middleware\HostHeaderMiddleware;
use App\Middleware\JsonBodyParserMiddleware;
use App\Service\DatabaseRuleProvider;
use App\Service\RuleSummarizer;
use Cake\Core\Configure;
use Cake\Core\ContainerInterface;
use Cake\Datasource\FactoryLocator;
use Cake\Error\Middleware\ErrorHandlerMiddleware;
use Cake\Event\EventManagerInterface;
use Cake\Http\BaseApplication;
use Cake\Http\Middleware\BodyParserMiddleware;
use Cake\Http\Middleware\CsrfProtectionMiddleware;
use Cake\Http\MiddlewareQueue;
use Cake\ORM\Locator\LocatorAwareTrait;
use Cake\ORM\Locator\TableLocator;
use Cake\Routing\Middleware\AssetMiddleware;
use Cake\Routing\Middleware\RoutingMiddleware;

/**
 * Application setup class.
 *
 * This defines the bootstrapping logic and middleware layers you
 * want to use in your application.
 *
 * @extends \Cake\Http\BaseApplication<\App\Application>
 */
class Application extends BaseApplication
{
    use LocatorAwareTrait;

    /**
     * Load all the application configuration and bootstrap logic.
     *
     * @return void
     */
    public function bootstrap(): void
    {
        // Call parent to load bootstrap from files.
        parent::bootstrap();

        // By default, does not allow fallback classes.
        FactoryLocator::add(
            'Table',
            (new TableLocator())->allowFallbackClass(false),
        );
    }

    /**
     * Setup the middleware queue your application will use.
     *
     * @param \Cake\Http\MiddlewareQueue $middlewareQueue The middleware queue to setup.
     * @return \Cake\Http\MiddlewareQueue The updated middleware queue.
     */
    public function middleware(MiddlewareQueue $middlewareQueue): MiddlewareQueue
    {
        $middlewareQueue
            // Catch any exceptions in the lower layers,
            // and make an error page/response
            ->add(new ErrorHandlerMiddleware(Configure::read('Error'), $this))

            // Validate Host header to prevent Host Header Injection attacks.
            // In production, ensures App.fullBaseUrl is configured and validates
            // the incoming Host header against it.
            ->add(new HostHeaderMiddleware())

            // Handle plugin/theme assets like CakePHP normally does.
            ->add(new AssetMiddleware([
                'cacheTime' => Configure::read('Asset.cacheTime'),
            ]))

            // Add routing middleware.
            // If you have a large number of routes connected, turning on routes
            // caching in production could improve performance.
            // See https://github.com/CakeDC/cakephp-cached-routing
            ->add(new RoutingMiddleware($this))


            // Parse various types of encoded request bodies so that they are
            // available as array through $request->getData()
            // https://book.cakephp.org/5/en/controllers/middleware.html#body-parser-middleware
            ->add(new BodyParserMiddleware());

            // Cross Site Request Forgery (CSRF) Protection Middleware
            // https://book.cakephp.org/5/en/security/csrf.html#cross-site-request-forgery-csrf-middleware
/*Disabled for now, as it is not necessary for demo use case.*/
//            ->add(new CsrfProtectionMiddleware([
//                'httponly' => true,
//            ]));

        return $middlewareQueue;
    }

    /**
     * Register application container services.
     *
     * @param \Cake\Core\ContainerInterface $container The Container to update.
     * @return void
     * @link https://book.cakephp.org/5/en/development/dependency-injection.html#dependency-injection
     */
    public function services(ContainerInterface $container): void
    {
        $container->add(RuleFactory::class, function (): RuleFactory {
            return new RuleFactory([
                MaxDocumentSizeRule::class,
                RequiredMetadataRule::class,
                ProhibitedWordsRule::class,
                MetadataAllowedValuesRule::class,
                ContentPatternRule::class,
            ]);
        });

        $container->add(RuleSummarizer::class);

        $container->add(ValidationRuleProvider::class, function () use ($container): DatabaseRuleProvider {
            $tables = $this->getTableLocator();

            return new DatabaseRuleProvider(
                $tables->get('Tenants'),
                $tables->get('TenantValidationRules'),
                $container->get(RuleFactory::class),
            );
        });

        $container->add(DocumentValidator::class)
            ->addArgument(ValidationRuleProvider::class);
    }

    /**
     * Register custom event listeners here
     *
     * @param \Cake\Event\EventManagerInterface $eventManager
     * @return \Cake\Event\EventManagerInterface
     * @link https://book.cakephp.org/5/en/core-libraries/events.html#registering-listeners
     */
    public function events(EventManagerInterface $eventManager): EventManagerInterface
    {
        // $eventManager->on(new SomeCustomListenerClass());

        return $eventManager;
    }
}
